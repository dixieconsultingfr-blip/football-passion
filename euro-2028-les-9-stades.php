            Situé au centre de Cardiff, ce stade est particulièrement connu pour les matchs de rugby de l'équipe galloise, mais il a également accueilli de grandes rencontres de football. Son toit rétractable permet d'organiser des matchs dans des conditions plus régulières, quelles que soient la météo et la saison.
        </p>
        <p class="text-gray-300 leading-relaxed">
            Cardiff accueillera le premier match de l'Euro 2028, le 9 juin, ainsi que plusieurs matchs de groupes, un huitième et un quart de finale — une rencontre inaugurale à la portée symbolique importante pour le pays de Galles, qui accueille pour la première fois un match d'un Championnat d'Europe masculin à domicile.
        </p>
